const normalizedTranslations = Object.fromEntries(
  Object.entries(translations).map(([source, target]) => [
    source.replace(/\s+/g, ' ').trim(),
    target
  ])
)

export default defineNuxtPlugin((nuxtApp) => {
  const languageSwitch = document.getElementById('language-switch')
  if (!languageSwitch) return

  const originalText = new WeakMap()
  let language = 'en'

  function translateTextNodes() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT)
    let node

    while ((node = walker.nextNode())) {
      if (!originalText.has(node)) originalText.set(node, node.nodeValue || '')
      const original = originalText.get(node)
      const trimmed = original.trim()
      if (!trimmed) continue

      const key = trimmed.replace(/\s+/g, ' ')
      let translated = trimmed
      if (language === 'en') {
        translated = normalizedTranslations[key] ?? trimmed
        translated = translated.replace(/(\d+) repositórios/g, '$1 repositories')
      }
      const leading = original.match(/^\s*/)?.[0] || ''
      const trailing = original.match(/\s*$/)?.[0] || ''
      const nextValue = leading + translated + trailing
      if (node.nodeValue !== nextValue) node.nodeValue = nextValue
    }
  }

  function setLanguage(nextLanguage) {
    language = nextLanguage
    document.documentElement.lang = language === 'en' ? 'en' : 'pt-PT'
    languageSwitch.setAttribute('aria-pressed', String(language === 'en'))
    languageSwitch.setAttribute(
      'aria-label',
      language === 'en' ? 'Switch language to Portuguese' : 'Mudar idioma para inglês'
    )
    document.title = language === 'en' ? 'Diogo Duarte Portfolio' : 'Portfólio Diogo Duarte'
    const donut = document.getElementById('donut')
    if (donut) {
      donut.setAttribute(
        'aria-label',
        language === 'en' ? 'ASCII animation of a rotating torus' : 'Animação ASCII de um toro a girar'
      )
    }

    const description = document.querySelector('meta[name="description"]')
    if (description) {
      description.setAttribute(
        'content',
        language === 'en'
          ? 'Diogo Duarte portfolio — front-end, full-stack development and multimedia.'
          : 'Portfólio de Diogo Duarte — desenvolvimento front-end, full stack e multimédia.'
      )
    }

    translateTextNodes()
    window.dispatchEvent(new CustomEvent('portfolio:language-change', { detail: { language } }))
  }

  nuxtApp.hook('app:mounted', () => {
    languageSwitch.addEventListener('click', () => {
      setLanguage(language === 'pt' ? 'en' : 'pt')
    })

    new MutationObserver(() => translateTextNodes()).observe(document.body, {
      childList: true,
      characterData: true,
      subtree: true
    })

    setLanguage(language)
  })
})
